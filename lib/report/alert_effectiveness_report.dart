import 'dart:math' as math;

import 'package:drift/drift.dart';

import '../data/local_db/database.dart';

/// One pre-alert together with the rider feedback (if any) that followed it.
class AlertEffectivenessEntry {
  final int preAlertId;
  final int? eventId;
  final int? roadEventId;
  final String eventType;
  final double distanceMeters;
  final double speedKmh;
  final double timeToEventSeconds;
  final double recommendedSpeedKmh;
  final String urgency;
  final String spokenText;
  final DateTime alertedAtUtc;

  final String? responseText;
  final String? responseSource;
  final double? effectiveness;
  final String? timingAdequacy;
  final String? difficulty;
  final String? riderSummary;
  final String? suggestion;
  final bool analyzedByLlm;

  const AlertEffectivenessEntry({
    required this.preAlertId,
    this.eventId,
    this.roadEventId,
    required this.eventType,
    required this.distanceMeters,
    required this.speedKmh,
    required this.timeToEventSeconds,
    required this.recommendedSpeedKmh,
    required this.urgency,
    required this.spokenText,
    required this.alertedAtUtc,
    this.responseText,
    this.responseSource,
    this.effectiveness,
    this.timingAdequacy,
    this.difficulty,
    this.riderSummary,
    this.suggestion,
    this.analyzedByLlm = false,
  });

  Map<String, dynamic> toJson() => {
        'pre_alert_id': preAlertId,
        'event_id': eventId,
        'road_event_id': roadEventId,
        'event_type': eventType,
        'distance_meters': distanceMeters,
        'speed_kmh': speedKmh,
        'time_to_event_seconds': timeToEventSeconds,
        'recommended_speed_kmh': recommendedSpeedKmh,
        'urgency': urgency,
        'spoken_text': spokenText,
        'alerted_at_utc': alertedAtUtc.toIso8601String(),
        'response_text': responseText,
        'response_source': responseSource,
        'alert_effectiveness': effectiveness,
        'alert_timing_adequacy': timingAdequacy,
        'difficulty_level': difficulty,
        'rider_summary': riderSummary,
        'improvement_suggestion': suggestion,
        'analyzed_by_llm': analyzedByLlm,
      };
}

/// Aggregated view of how well the predictive pre-alert system performed.
class AlertEffectivenessReport {
  final int totalAlerts;
  final int totalFeedback;
  final int analyzedByLlm;
  final int alertsWithFeedback;

  /// Mean LLM-assigned effectiveness (0..1) across alerts with feedback.
  final double averageEffectiveness;

  /// Mean time-to-event at which warnings were issued.
  final double averageTimeToEventSeconds;

  /// Mean distance at which warnings were issued.
  final double averageDistanceMeters;

  /// adequate / too_early / too_late / unknown counts.
  final Map<String, int> timingBreakdown;

  /// event type -> alert count.
  final Map<String, int> eventTypeBreakdown;

  /// event type -> mean effectiveness.
  final Map<String, double> effectivenessByEventType;

  /// Compiled, human-readable insights.
  final List<String> insights;

  final List<AlertEffectivenessEntry> entries;

  const AlertEffectivenessReport({
    this.totalAlerts = 0,
    this.totalFeedback = 0,
    this.analyzedByLlm = 0,
    this.alertsWithFeedback = 0,
    this.averageEffectiveness = 0,
    this.averageTimeToEventSeconds = 0,
    this.averageDistanceMeters = 0,
    this.timingBreakdown = const {},
    this.eventTypeBreakdown = const {},
    this.effectivenessByEventType = const {},
    this.insights = const [],
    this.entries = const [],
  });

  bool get isEmpty => totalAlerts == 0 && totalFeedback == 0;

  Map<String, dynamic> toJson() => {
        'total_alerts': totalAlerts,
        'total_feedback': totalFeedback,
        'alerts_with_feedback': alertsWithFeedback,
        'analyzed_by_llm': analyzedByLlm,
        'average_effectiveness': averageEffectiveness,
        'average_time_to_event_seconds': averageTimeToEventSeconds,
        'average_distance_meters': averageDistanceMeters,
        'timing_breakdown': timingBreakdown,
        'event_type_breakdown': eventTypeBreakdown,
        'effectiveness_by_event_type': effectivenessByEventType,
        'insights': insights,
        'entries': entries.map((e) => e.toJson()).toList(),
      };

  /// Renders the report as a Markdown document (shipped with the export).
  String toMarkdown() {
    final buffer = StringBuffer();
    buffer.writeln('# Predictive Pre-Alert Effectiveness Report');
    buffer.writeln();
    buffer.writeln('## Summary');
    buffer.writeln();
    buffer.writeln('| Metric | Value |');
    buffer.writeln('|---|---|');
    buffer.writeln('| Pre-alerts issued | $totalAlerts |');
    buffer.writeln('| Rider feedback records | $totalFeedback |');
    buffer.writeln('| Alerts with feedback | $alertsWithFeedback |');
    buffer.writeln('| Analyses generated by LLM | $analyzedByLlm |');
    buffer.writeln(
        '| Average effectiveness | ${averageEffectiveness.toStringAsFixed(3)} |');
    buffer.writeln(
        '| Average time-to-event (s) | ${averageTimeToEventSeconds.toStringAsFixed(1)} |');
    buffer.writeln(
        '| Average warning distance (m) | ${averageDistanceMeters.toStringAsFixed(0)} |');
    buffer.writeln();

    if (timingBreakdown.isNotEmpty) {
      buffer.writeln('## Warning Timing');
      buffer.writeln();
      buffer.writeln('| Timing | Count |');
      buffer.writeln('|---|---|');
      timingBreakdown.forEach((k, v) => buffer.writeln('| $k | $v |'));
      buffer.writeln();
    }

    if (eventTypeBreakdown.isNotEmpty) {
      buffer.writeln('## Alerts by Event Type');
      buffer.writeln();
      buffer.writeln('| Event type | Alerts | Mean effectiveness |');
      buffer.writeln('|---|---|---|');
      eventTypeBreakdown.forEach((k, v) {
        final eff = effectivenessByEventType[k];
        buffer.writeln('| $k | $v | ${eff?.toStringAsFixed(3) ?? 'n/a'} |');
      });
      buffer.writeln();
    }

    buffer.writeln('## Insights');
    buffer.writeln();
    if (insights.isEmpty) {
      buffer.writeln('_No insights available yet._');
    } else {
      for (final insight in insights) {
        buffer.writeln('- $insight');
      }
    }
    buffer.writeln();

    if (entries.isNotEmpty) {
      buffer.writeln('## Per-Alert Detail');
      buffer.writeln();
      buffer.writeln(
          '| Time (UTC) | Type | Distance (m) | TTE (s) | Speed (km/h) | Recommended | Effectiveness | Timing | Rider said |');
      buffer.writeln('|---|---|---|---|---|---|---|---|---|');
      for (final e in entries) {
        buffer.writeln('| ${e.alertedAtUtc.toIso8601String()} | ${e.eventType} | '
            '${e.distanceMeters.toStringAsFixed(0)} | '
            '${e.timeToEventSeconds.toStringAsFixed(1)} | '
            '${e.speedKmh.toStringAsFixed(1)} | '
            '${e.recommendedSpeedKmh.toStringAsFixed(0)} | '
            '${e.effectiveness?.toStringAsFixed(2) ?? 'n/a'} | '
            '${e.timingAdequacy ?? 'n/a'} | '
            '${_escape(e.responseText ?? '')} |');
      }
      buffer.writeln();
    }

    return buffer.toString();
  }

  static String _escape(String value) {
    return value.replaceAll('|', r'\|').replaceAll('\n', ' ');
  }
}

/// Builds an [AlertEffectivenessReport] from the persisted pre-alert and
/// feedback tables.
class AlertEffectivenessReportBuilder {
  final AppDatabase _db;

  AlertEffectivenessReportBuilder(this._db);

  Future<AlertEffectivenessReport> build({
    DateTime? startUtc,
    DateTime? endUtc,
    int? tripId,
  }) async {
    var alertQuery = _db.select(_db.preAlerts)
      ..orderBy([(t) => OrderingTerm(expression: t.alertedAtUtc)]);
    if (startUtc != null) {
      alertQuery = alertQuery
        ..where((t) => t.alertedAtUtc.isBiggerOrEqualValue(startUtc));
    }
    if (endUtc != null) {
      alertQuery = alertQuery..where((t) => t.alertedAtUtc.isSmallerOrEqualValue(endUtc));
    }
    if (tripId != null) {
      alertQuery = alertQuery..where((t) => t.tripId.equals(tripId));
    }
    final alerts = await alertQuery.get();

    var feedbackQuery = _db.select(_db.eventFeedbacks)
      ..orderBy([(t) => OrderingTerm(expression: t.createdAtUtc)]);
    if (startUtc != null) {
      feedbackQuery = feedbackQuery
        ..where((t) => t.createdAtUtc.isBiggerOrEqualValue(startUtc));
    }
    if (endUtc != null) {
      feedbackQuery = feedbackQuery
        ..where((t) => t.createdAtUtc.isSmallerOrEqualValue(endUtc));
    }
    if (tripId != null) {
      feedbackQuery = feedbackQuery..where((t) => t.tripId.equals(tripId));
    }
    final feedbackList = await feedbackQuery.get();

    // Index feedback by preAlertId and by eventId so alerts can be matched.
    final byPreAlertId = <int, EventFeedback>{};
    final byEventId = <int, EventFeedback>{};
    for (final fb in feedbackList) {
      if (fb.preAlertId != null) byPreAlertId[fb.preAlertId!] = fb;
      if (fb.eventId != null) byEventId[fb.eventId!] = fb;
    }

    final entries = <AlertEffectivenessEntry>[];
    for (final alert in alerts) {
      final fb = byPreAlertId[alert.id] ??
          (alert.eventId != null ? byEventId[alert.eventId!] : null);
      entries.add(
        AlertEffectivenessEntry(
          preAlertId: alert.id,
          eventId: alert.eventId,
          roadEventId: alert.roadEventId,
          eventType: alert.eventType,
          distanceMeters: alert.distanceMeters,
          speedKmh: alert.speedKmh,
          timeToEventSeconds: alert.timeToEventSeconds,
          recommendedSpeedKmh: alert.recommendedSpeedKmh,
          urgency: alert.urgency,
          spokenText: alert.spokenText,
          alertedAtUtc: alert.alertedAtUtc,
          responseText: fb?.responseText,
          responseSource: fb?.responseSource,
          effectiveness: fb?.alertEffectiveness,
          timingAdequacy: fb?.alertTimingAdequacy,
          difficulty: fb?.difficultyLevel,
          riderSummary: fb?.riderSummary,
          suggestion: fb?.improvementSuggestion,
          analyzedByLlm: fb?.analyzedByLlm ?? false,
        ),
      );
    }

    final timingBreakdown = <String, int>{};
    final eventTypeBreakdown = <String, int>{};
    final effectivenessSums = <String, double>{};
    final effectivenessCounts = <String, int>{};

    var effectivenessSum = 0.0;
    var effectivenessCount = 0;
    var tteSum = 0.0;
    var distanceSum = 0.0;
    var withFeedback = 0;
    var llmCount = 0;

    for (final entry in entries) {
      eventTypeBreakdown.update(
        entry.eventType,
        (v) => v + 1,
        ifAbsent: () => 1,
      );
      tteSum += entry.timeToEventSeconds;
      distanceSum += entry.distanceMeters;

      if (entry.effectiveness != null) {
        final timing = entry.timingAdequacy ?? 'unknown';
        timingBreakdown.update(timing, (v) => v + 1, ifAbsent: () => 1);
        effectivenessSum += entry.effectiveness!;
        effectivenessCount++;
        withFeedback++;
        effectivenessSums.update(
          entry.eventType,
          (v) => v + entry.effectiveness!,
          ifAbsent: () => entry.effectiveness!,
        );
        effectivenessCounts.update(
          entry.eventType,
          (v) => v + 1,
          ifAbsent: () => 1,
        );
        if (entry.analyzedByLlm) llmCount++;
      }
    }

    final effectivenessByEventType = <String, double>{
      for (final key in effectivenessCounts.keys)
        key: effectivenessSums[key]! / effectivenessCounts[key]!,
    };

    final insights = _compileInsights(
      entries: entries,
      timingBreakdown: timingBreakdown,
      averageEffectiveness:
          effectivenessCount == 0 ? 0 : effectivenessSum / effectivenessCount,
      averageTte: entries.isEmpty ? 0 : tteSum / entries.length,
    );

    return AlertEffectivenessReport(
      totalAlerts: entries.length,
      totalFeedback: feedbackList.length,
      analyzedByLlm: llmCount,
      alertsWithFeedback: withFeedback,
      averageEffectiveness:
          effectivenessCount == 0 ? 0 : effectivenessSum / effectivenessCount,
      averageTimeToEventSeconds: entries.isEmpty ? 0 : tteSum / entries.length,
      averageDistanceMeters: entries.isEmpty ? 0 : distanceSum / entries.length,
      timingBreakdown: timingBreakdown,
      eventTypeBreakdown: eventTypeBreakdown,
      effectivenessByEventType: effectivenessByEventType,
      insights: insights,
      entries: entries,
    );
  }

  List<String> _compileInsights({
    required List<AlertEffectivenessEntry> entries,
    required Map<String, int> timingBreakdown,
    required double averageEffectiveness,
    required double averageTte,
  }) {
    final insights = <String>[];

    if (entries.isEmpty) {
      insights.add(
          'No predictive pre-alerts were issued in this range, so no timing calibration is available yet.');
      return insights;
    }

    final late = timingBreakdown['too_late'] ?? 0;
    final early = timingBreakdown['too_early'] ?? 0;
    final adequate = timingBreakdown['adequate'] ?? 0;

    insights.add(
        '$late of ${timingBreakdown.values.fold<int>(0, (a, b) => a + b)} evaluated warnings were judged too late, '
        '$early too early and $adequate adequately timed.');

    if (averageEffectiveness > 0) {
      insights.add(
          'Mean warning effectiveness was ${averageEffectiveness.toStringAsFixed(2)} '
          '(1.0 = perfectly timed).');
    }

    insights.add(
        'Warnings were issued on average ${averageTte.toStringAsFixed(1)} seconds before the event.');

    // Surface the LLM's concrete tuning suggestions (deduplicated).
    final suggestions = <String>[];
    for (final entry in entries) {
      final suggestion = entry.suggestion?.trim();
      if (suggestion == null || suggestion.isEmpty) continue;
      if (!suggestions.contains(suggestion)) suggestions.add(suggestion);
    }
    insights.addAll(suggestions.take(5));

    // Highlight the worst-performing event type.
    String? worstType;
    var worstScore = double.infinity;
    final byType = <String, List<double>>{};
    for (final entry in entries) {
      final eff = entry.effectiveness;
      if (eff == null) continue;
      byType.putIfAbsent(entry.eventType, () => []).add(eff);
    }
    byType.forEach((type, values) {
      final avg = values.reduce((a, b) => a + b) / values.length;
      if (avg < worstScore) {
        worstScore = avg;
        worstType = type;
      }
    });
    if (worstType != null && worstScore < 0.6) {
      insights.add(
          '$worstType events scored lowest (${worstScore.toStringAsFixed(2)}); '
          'consider tuning the detection threshold or the warning distance for this class.');
    }

    return insights;
  }

  /// Computes a mean, guarding against an empty list.
  static double mean(List<double> values) {
    if (values.isEmpty) return 0;
    return values.reduce((a, b) => a + b) / values.length;
  }

  /// Clamp helper.
  static double clamp01(double v) => math.max(0.0, math.min(1.0, v));
}
